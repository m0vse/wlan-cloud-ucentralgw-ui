const fs = require('fs'), ts = require('typescript'), vm = require('vm'), assert = require('assert');
const context = { exports: {}, Map };
vm.runInNewContext(ts.transpileModule(fs.readFileSync('src/helpers/neighbourData.ts', 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 } }).outputText, context);
const normalize = context.exports.normalizeNeighbours;
const row = { bssid: 'AA:BB:CC:DD:EE:FF', frequency: 5180, channel: 36, signal: -65, ssid: '<test>' };
assert.strictEqual(normalize(null).length, 0);
assert.strictEqual(normalize([row])[0].bssid, row.bssid.toLowerCase());
assert.strictEqual(normalize([row])[0].ssid, '<test>');
assert.strictEqual(normalize([row, {...row, signal: -55}]).length, 1);
assert.strictEqual(normalize([row, {...row, signal: -55}])[0].signal, -55);
for (const signal of [NaN, Infinity, 0, -151, 'garbage']) assert.strictEqual(normalize([{...row, signal}]).length, 0);
assert.strictEqual(normalize([{...row, bssid: 'unknown'}]).length, 0);
assert.strictEqual(normalize([{...row, ssid: ''}])[0].ssid, '(hidden)');
assert.strictEqual(context.exports.neighbourBand(2412), '2.4 GHz');
assert.strictEqual(context.exports.neighbourBand(5180), '5 GHz');
assert.strictEqual(context.exports.neighbourBand(5955), '6 GHz');
console.log('PASS: neighbour normalization, deduplication, signal validation, hidden SSIDs and band boundaries');
const panel = fs.readFileSync('src/pages/Device/NeighbourCoverage.tsx', 'utf8');
assert(panel.includes('<CardBody display="block">'));
assert(!panel.includes('Signals observed by this AP'));
assert(!panel.includes('Signal bars use a fixed'));
console.log('PASS: vertical card layout and concise panel text');
assert(panel.includes('<details>') && !panel.includes('<details open'));
assert(panel.includes('ownRadios={ownRadios}'));
const graph = fs.readFileSync('src/pages/Device/SignalGraph.tsx', 'utf8');
assert(graph.includes('strokeDasharray="5 4"'));
assert(graph.includes('20 MHz display width'));
assert(graph.indexOf('React.useState') < graph.indexOf('return null'));
console.log('PASS: per-band channel curves, distinct own-AP overlay and collapsed details');
const React = { useState: () => [undefined, () => {}], createElement: (type, props, ...children) => ({type, props, children}) };
const graphContext = { exports: {}, require: (name) => name === 'react' ? React : name === '@chakra-ui/react' ? { Box: 'box', Heading: 'heading', Text: 'text' } : context.exports };
vm.runInNewContext(ts.transpileModule(graph, { compilerOptions: { module: ts.ModuleKind.CommonJS, jsx: ts.JsxEmit.React, target: ts.ScriptTarget.ES2020 } }).outputText, graphContext);
const renderGraph = graphContext.exports.default;
assert.strictEqual(renderGraph({rows: [], band: '5 GHz'}), null);
const rendered = JSON.stringify(renderGraph({rows: normalize([row]), band: '5 GHz', ownRadios: [{frequency: 5180, channel: 36, label: 'My AP', txPower: 20}]}));
assert(rendered.includes('My AP') && rendered.includes('TX 20 dBm') && rendered.includes('path') && rendered.includes('rect'));
assert(!rendered.includes('NaN') && !rendered.includes('Infinity'));
assert(JSON.stringify(renderGraph({rows: [], band: '6 GHz', ownRadios: [{frequency: 5955, channel: 1, label: 'Own 6G'}]})).includes('Own 6G'));
console.log('PASS: rendered curves and own-channel overlays, including own-only bands');
