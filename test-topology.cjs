const fs = require('fs'), ts = require('typescript'), vm = require('vm'), assert = require('assert');
const context = {exports:{}};
vm.runInNewContext(ts.transpileModule(fs.readFileSync('src/helpers/radioTopology.ts','utf8'), {compilerOptions:{module:ts.ModuleKind.CommonJS}}).outputText, context);
const {readRadioTopology: read, mergeRadioTopology: merge, isTopologyDevice} = context.exports;
const snapshot = (active,desired,reboot_required,recorded=100) => ({recorded,data:{unit:{cambium:{radio_topology:{active,desired,reboot_required}}}}});
const pending = read(snapshot('dual-4x4','single-8x8',true));
assert(pending.pending);
assert(read(snapshot('dual-4x4','single-8x8',false)).pending);
assert(!read(snapshot('single-8x8','single-8x8',false,110)).pending);
assert(!read(snapshot('dual-4x4','dual-4x4',false)).pending);
assert.strictEqual(read(snapshot('bad','single-8x8',true)),undefined);
assert.strictEqual(read({}),undefined);
assert.strictEqual(merge(pending,undefined),pending);
assert.strictEqual(merge(pending,read(snapshot('dual-4x4','dual-4x4',false,99))),pending);
assert(!merge(pending,read(snapshot('single-8x8','single-8x8',false,110))).pending);
assert.strictEqual(merge(pending,read(snapshot('single-8x8','single-8x8',false,100))),pending);
assert(isTopologyDevice({compatible:'cambium-xv3-8'}));
assert(!isTopologyDevice({compatible:'cambium-e410'}));
const wrapper=fs.readFileSync('src/pages/Device/Wrapper.tsx','utf8');
assert(wrapper.includes('onReboot={rebootModalProps.onOpen}'));
const warning=fs.readFileSync('src/pages/Device/TopologyWarning.tsx','utf8');
assert(!warning.includes('mutate') && warning.includes('onClick={onReboot}'));
console.log('PASS: pending/staged topology, fresh confirmation, stale/missing preservation, model filtering and existing reboot confirmation');
const {readRebootRequirement: readReboot, mergeRebootRequirement: mergeReboot} = context.exports;
const generic = (reboot_required,recorded) => ({recorded,data:{unit:{reboot_required}}});
assert(readReboot(generic(true,100)).pending);
assert(!readReboot(generic(false,100)).pending);
assert(readReboot({recorded:100,data:{unit:{cambium:{reboot_required:true}}}}).pending);
const staged=readReboot(snapshot('dual-4x4','single-8x8',true));
assert(mergeReboot(staged,readReboot(generic(false,110))).pending);
assert(!mergeReboot(staged,readReboot(snapshot('single-8x8','single-8x8',false,110))).pending);
assert.strictEqual(mergeReboot(staged,undefined),staged);
assert.strictEqual(mergeReboot(staged,readReboot(generic(false,90))),staged);
assert(warning.includes('>Reboot required</Text>'));
console.log('PASS: generic AP reboot flags, independent reasons and explicit fresh confirmation');
